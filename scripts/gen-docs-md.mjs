#!/usr/bin/env bun
// Renders the console's own documentation screen as markdown.
//
// The /docs screen and these files must never disagree, so the markdown is not
// written by hand: it is rendered from the same two modules the Vue view reads.
//   - web/src/lib/docs-content.js  machine data, identical in every locale
//   - web/src/lib/copy/*.js        prose, per language
// Run `make docs-md` after changing an endpoint or a translation.
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import {
  adapterCodes,
  a2aAliases,
  a2aMethods,
  a2aShapes,
  docsSections,
  endpointGroups,
  errorGroups,
  healthStates,
  httpEndpoints,
  recordStatuses,
  resourceKinds,
  taskStates,
} from '../web/src/lib/docs-content.js'
import { docsCopy } from '../web/src/lib/copy/docs-copy.js'
import { enumsCopy } from '../web/src/lib/copy/enums-copy.js'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

/** Same resolution the console uses: English block, then the language on top. */
function resolve(copy, lang) {
  return { ...copy.en, ...(copy[lang] || {}) }
}

/** Same fallback as enumLabel: the raw value when no label exists. */
function enumLabel(group, value, lang) {
  if (!value) return ''
  const table = resolve(enumsCopy[group] || {}, lang)
  return table[value] || value
}

function t(dict, key) {
  return dict[key] ?? key
}

/** Endpoint rows are templated: the verb takes the noun as {n}. */
function descFor(dict, endpoint) {
  const template = t(dict, endpoint.descKey)
  if (!endpoint.nounKey) return template
  return template.replace('{n}', t(dict, endpoint.nounKey))
}

/** A cell may not contain an unescaped pipe or a raw newline. */
const cell = (value) => String(value ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ')

const row = (cells) => `| ${cells.map(cell).join(' | ')} |`

function table(header, rows) {
  return [row(header), row(header.map(() => '---')), ...rows.map(row)].join('\n')
}

/**
 * A lifecycle is not a straight line: the head runs in order and the tail is a
 * set of alternatives. `submitted → working → input-required → completed |
 * failed | canceled` reads correctly; six arrows in a row would not.
 */
function flow(values) {
  return `${values.slice(0, 3).join(' → ')} → ${values.slice(3).join(' | ')}`
}

function fenced(body) {
  return `\`\`\`json\n${body}\n\`\`\``
}

function render(lang) {
  const dict = resolve(docsCopy, lang)
  const out = []

  out.push(
    '<!-- Generated by scripts/gen-docs-md.mjs from web/src/lib/docs-content.js and',
    '     web/src/lib/copy/docs-copy.js — the same modules the /docs screen reads.',
    '     Run `make docs-md` to regenerate. Do not edit by hand. -->',
    '',
    `# agenthub ${t(dict, 'pageTitle')}`,
    '',
    t(dict, 'pageSub'),
    '',
    // No trailing period: each translation ends its own way, and a CJK line
    // should not be closed with an ASCII full stop.
    `> ${t(dict, 'versionNote')}`,
    '',
  )

  // --- Concepts ---
  out.push(`## ${t(dict, 'sectionConcepts')}`, '', t(dict, 'conceptsBody'), '')
  out.push(
    `### ${t(dict, 'kindsTitle')}`,
    '',
    table(
      [t(dict, 'colKind'), t(dict, 'colKindRole')],
      resourceKinds.map((lane) => [enumLabel('kind', lane.kind, lang), t(dict, lane.descKey)]),
    ),
    '',
  )
  out.push(
    `### ${t(dict, 'lifecycleTitle')}`,
    '',
    `\`${flow(taskStates.map((state) => enumLabel('taskState', state, lang)))}\``,
    '',
    t(dict, 'lifecycleNote'),
    '',
  )
  // Health has no order: it is a set of values, so a chain of arrows would lie.
  out.push(
    `### ${t(dict, 'healthTitle')}`,
    '',
    healthStates.map((state) => `**${enumLabel('health', state, lang)}**`).join(' · '),
    '',
    t(dict, 'healthNote'),
    '',
  )
  out.push(
    `### ${t(dict, 'statusTitle')}`,
    '',
    `\`${flow(recordStatuses.map((status) => enumLabel('status', status, lang)))}\``,
    '',
    t(dict, 'statusNote'),
    '',
  )

  // --- A2A ---
  out.push(`## ${t(dict, 'sectionA2a')}`, '', t(dict, 'a2aBody'), '')
  out.push(
    table(
      [t(dict, 'colMethod'), t(dict, 'colDescription'), t(dict, 'colParams'), t(dict, 'colResponse')],
      a2aMethods.map((method) => [
        `\`${method.method}\``,
        t(dict, method.descKey),
        `\`${method.params}\``,
        `\`${method.response}\``,
      ]),
    ),
    '',
    t(dict, 'methodsNote'),
    '',
    `### ${t(dict, 'aliasesTitle')}`,
    '',
    a2aAliases.map((alias) => `- \`${alias.alias}\` → \`${alias.method}\``).join('\n'),
    '',
    `### ${t(dict, 'shapesTitle')}`,
    '',
  )
  for (const shape of a2aShapes) {
    out.push(`**${shape.title}**`, '', fenced(shape.body), '')
  }

  // --- HTTP API ---
  out.push(`## ${t(dict, 'sectionHttp')}`, '', t(dict, 'httpBody'), '')
  const header = [
    t(dict, 'colMethod'),
    t(dict, 'colPath'),
    t(dict, 'colPermission'),
    t(dict, 'colDescription'),
    t(dict, 'colRequest'),
    t(dict, 'colResponse'),
  ]
  for (const group of endpointGroups) {
    out.push(
      `### ${t(dict, group.groupKey)}`,
      '',
      table(
        header,
        httpEndpoints
          .filter((endpoint) => endpoint.group === group.id)
          .map((endpoint) => [
            `\`${endpoint.method}\``,
            `\`${endpoint.path}\``,
            endpoint.permission
              ? `\`${endpoint.permission}\` — ${enumLabel('permission', endpoint.permission, lang)}`
              : '—',
            descFor(dict, endpoint),
            endpoint.request ? `\`${endpoint.request}\`` : '—',
            `\`${endpoint.response}\``,
          ]),
      ),
      '',
    )
  }
  out.push(t(dict, 'endpointsNote'), '')

  // --- Authentication ---
  out.push(
    `## ${t(dict, 'sectionAuth')}`,
    '',
    t(dict, 'authBody'),
    '',
    `### ${t(dict, 'authSessionTitle')}`,
    '',
    t(dict, 'authSessionBody'),
    '',
    `### ${t(dict, 'authPermTitle')}`,
    '',
    t(dict, 'authPermBody'),
    '',
    t(dict, 'authOwnerNote'),
    '',
    `### ${t(dict, 'authApiKeyTitle')}`,
    '',
    t(dict, 'authApiKeyBody'),
    '',
    t(dict, 'authApiKeyScopeNote'),
    '',
  )

  // --- Errors ---
  out.push(`## ${t(dict, 'sectionErrors')}`, '', t(dict, 'errorsBody'), '')
  out.push(
    table(
      [t(dict, 'colStatus'), t(dict, 'colMeaning'), t(dict, 'colCode')],
      errorGroups.map((group) => [`\`${group.status}\``, group.reason, `\`${group.codes}\``]),
    ),
    '',
    t(dict, 'errorBodyNote'),
    '',
    `### ${t(dict, 'adapterTitle')}`,
    '',
    table(
      [t(dict, 'colCode'), t(dict, 'colMeaning')],
      adapterCodes.map((entry) => [`\`${entry.code}\``, t(dict, entry.meaningKey)]),
    ),
    '',
  )

  out.push(
    '---',
    '',
    `Sections: ${docsSections.map((section) => t(dict, section.titleKey)).join(' · ')}`,
    '',
  )

  return out.join('\n')
}

const targets = [
  { lang: 'en', file: 'docs/docs.md' },
  { lang: 'zh', file: 'docs/docs_cn.md' },
]

mkdirSync(join(root, 'docs'), { recursive: true })
for (const { lang, file } of targets) {
  const path = join(root, file)
  writeFileSync(path, render(lang))
  console.log(`${file} (${lang})`)
}
